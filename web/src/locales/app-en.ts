/**
 * English catalog for the authenticated application (everything behind the
 * login). This shape is the contract: every other locale file is typed as
 * AppStrings = typeof appEn, so TypeScript rejects any missing or extra leaf
 * at compile time — a locale cannot silently fall back to English.
 *
 * Conventions:
 * - `{placeholders}` are filled by interpolate(); never concatenate translated
 *   fragments, word order differs per language.
 * - Plural-bearing strings use a Plural object ({ one, few, many, other });
 *   the plural() helper picks the form via Intl.PluralRules for the locale.
 * - Provider names (Google Drive, Dropbox, OneDrive, pCloud, MEGA, Cloudflare)
 *   and the CloudNest brand stay untranslated.
 * - User-owned file names, folder names and provider-returned content are
 *   never passed through the catalog — they are data, interpolated as-is.
 */
